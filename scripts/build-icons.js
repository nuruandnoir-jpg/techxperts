// Generates public/icons.js from the Heroicons package (https://heroicons.com, MIT).
// Only the icons listed here are included. Run: npm run icons
import { readFileSync, writeFileSync } from 'node:fs';

// [name used in the app, Heroicons file]
const ICONS = [
  ['menu', '24/outline/bars-3'],
  ['close', '24/outline/x-mark'],
  ['sparkles', '20/solid/sparkles'],
  ['briefcase', '20/solid/briefcase'],
  ['sun', '24/outline/sun'],
  ['moon', '24/outline/moon'],
  ['arrow-up-right', '20/solid/arrow-up-right'],
  ['arrow-right', '20/solid/arrow-right'],
  ['arrow-left', '20/solid/arrow-left'],
  ['check', '20/solid/check'],
  ['star', '20/solid/star'],
  ['plus', '20/solid/plus'],
  ['code', '24/outline/code-bracket'],
  ['ai', '24/outline/cpu-chip'],
  ['wrench', '24/outline/wrench-screwdriver'],
  ['cloud', '24/outline/cloud'],
  ['bulb', '24/outline/light-bulb'],
  ['shield', '24/outline/shield-check'],
  ['mobile', '24/outline/device-phone-mobile'],
  ['design', '24/outline/paint-brush'],
  ['data', '24/outline/circle-stack'],
  ['bug', '24/outline/bug-ant'],
  ['chart', '24/outline/chart-bar'],
  ['server', '24/outline/server-stack'],
  ['terminal', '24/outline/command-line'],
];

const entries = ICONS.map(([name, file]) => {
  const svg = readFileSync(new URL(`../node_modules/heroicons/${file}.svg`, import.meta.url), 'utf8');
  const open = svg.match(/<svg([^>]*)>/)[1];
  const attrs = ['viewBox', 'fill', 'stroke', 'stroke-width']
    .map((a) => open.match(new RegExp(`\\s${a}="([^"]*)"`)))
    .filter(Boolean)
    .map((m) => m[0].trim())
    .join(' ');
  const inner = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '');
  return `  ${JSON.stringify(name)}: [${JSON.stringify(attrs)}, ${JSON.stringify(inner)}],`;
});

writeFileSync(
  new URL('../public/icons.js', import.meta.url),
  `// Icons from Heroicons (https://heroicons.com), MIT License, Copyright (c) Tailwind Labs, Inc.
// Generated by scripts/build-icons.js; do not edit by hand.
const ICONS = {
${entries.join('\n')}
};

/** Returns an inline SVG string. Icons use currentColor and are hidden from screen readers. */
export function icon(name, { size = 20, cls = '' } = {}) {
  const [attrs, inner] = ICONS[name];
  return \`<svg xmlns="http://www.w3.org/2000/svg" \${attrs} width="\${size}" height="\${size}" class="icon \${cls}" aria-hidden="true" focusable="false">\${inner}</svg>\`;
}
`,
);
console.log(`Wrote public/icons.js (${ICONS.length} icons)`);
